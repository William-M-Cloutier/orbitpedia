#!/usr/bin/env node
/**
 * Generates src/data/catalog.generated.ts from systems/*.json + bodies/*.json.
 * Run after ingest / when adding body cards. Keeps catalog.ts free of hand imports.
 *
 *   node scripts/generate-catalog-index.mjs
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DATA_DIR = join(HERE, "..", "src", "data");
const BODIES_DIR = join(DATA_DIR, "bodies");
const SYSTEMS_DIR = join(DATA_DIR, "systems");
const OUT = join(DATA_DIR, "catalog.generated.ts");

function listJson(dir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort((a, b) => a.localeCompare(b));
}

function ident(prefix, file) {
  const base = file.replace(/\.json$/, "");
  const safe = base.replace(/[^a-zA-Z0-9_]/g, "_");
  const lead = /^[0-9]/.test(safe) ? `_${safe}` : safe;
  return `${prefix}_${lead}`;
}

const systemFiles = listJson(SYSTEMS_DIR);
const bodyFiles = listJson(BODIES_DIR);

if (systemFiles.length === 0) {
  console.error("generate-catalog-index: no systems/*.json found");
  process.exit(1);
}
if (bodyFiles.length === 0) {
  console.error("generate-catalog-index: no bodies/*.json found");
  process.exit(1);
}

const lines = [];
lines.push(
  "/* AUTO-GENERATED by scripts/generate-catalog-index.mjs — do not edit by hand */",
  "/* eslint-disable */",
  "",
);
for (const f of systemFiles) {
  lines.push(`import ${ident("system", f)} from "./systems/${f}";`);
}
lines.push("");
for (const f of bodyFiles) {
  lines.push(`import ${ident("body", f)} from "./bodies/${f}";`);
}
lines.push("");
lines.push(
  `export const loadedSystems = [${systemFiles.map((f) => ident("system", f)).join(", ")}];`,
);
lines.push(
  `export const loadedBodies = [${bodyFiles.map((f) => ident("body", f)).join(", ")}];`,
);
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(
  `Wrote ${OUT} (${systemFiles.length} systems, ${bodyFiles.length} bodies)`,
);
